import { readFileSync, writeFileSync } from "node:fs"

const source = readFileSync(
  new URL("../../packages/core/.mercur/routes.d.ts", import.meta.url),
  "utf8",
)
const sections = source.match(/^    (?:auth|admin|vendor): \{[\s\S]*?^    \};/gm)
if (sections?.length !== 3) {
  throw new Error("Expected native Mercur auth/admin/vendor route declarations")
}
for (const [host, role] of [["admin-test", "admin"], ["vendor", "vendor"]]) {
  const selected = sections.filter((section) =>
    section.startsWith("    auth:") || section.startsWith(`    ${role}:`),
  )
  const routes = selected.join("\n").replaceAll('"../src/', '"@mercurjs/core/')
  if (routes.includes("../src/")) {
    throw new Error("Native panel contract must not import backend source")
  }
  const output = "// Generated by shared/p01/generate-native-contract.mjs from native Mercur routes.\n"
    + "// Resolve compiled native declarations; never import backend implementation source.\n"
    + "export type NativeRoutes = {\n" + routes + "\n};\n"
  writeFileSync(new URL(`../../apps/${host}/src/lib/native-routes.d.ts`, import.meta.url), output)
}
console.log("Generated native panel contracts (auth/admin and auth/vendor)")
