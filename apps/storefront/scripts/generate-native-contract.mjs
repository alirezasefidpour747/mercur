import { readFileSync, writeFileSync } from "node:fs"

const source = readFileSync(
  new URL("../../../packages/core/.mercur/routes.d.ts", import.meta.url),
  "utf8",
)
const sections = source.match(/^    (?:auth|store): \{[\s\S]*?^    \};/gm)
if (sections?.length !== 2) {
  throw new Error("Expected native Mercur auth and store route declarations")
}
const routes = sections.join("\n").replaceAll('"../src/', '"@mercurjs/core/')
if (routes.includes("../src/")) {
  throw new Error("Native contract must not import backend source")
}
const output = `// Generated by scripts/generate-native-contract.mjs from Mercur's native route map.
// Native routes use compiled package declarations, never backend TypeScript source.
// Regenerate with bun run generate:native-contract; do not hand-edit.

export type NativeRoutes = {
${routes}
};
`
writeFileSync(new URL("../src/lib/native-routes.d.ts", import.meta.url), output)
console.log("Generated native storefront contract (auth/store)")
